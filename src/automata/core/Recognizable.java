package automata.core;

/**
 * Дефинира договор за обект, който може да разпознава думи от език.
 *
 * <p>Имплементира се от {@link Automaton} и позволява полиморфна работа с
 * автомати чрез абстракция, независима от конкретната реализация.</p>
 */
public interface Recognizable {

    /**
     * Проверява дали дадена дума се разпознава (приема) от автомата.
     *
     * @param word думата за проверка
     * @return {@code true}, ако думата принадлежи на езика на автомата
     */
    boolean recognize(String word);

    /**
     * Проверява дали езикът на автомата е празен.
     *
     * @return {@code true}, ако автоматът не приема нито една дума
     */
    boolean isEmpty();
}